# Same format as engine/news_words.py: {fact} is filled in by the code, #name#
# drops in a pick from another list, (text, "needs") entries are only used when
# those facts are true (and are favored when they are, so the angle that fits
# what happened wins over the plain lines).
#
# Rewritten Oct 24 (Blake: "the tweets that are visible feel completely new and
# in reaction to whats happening... there should not be word for word repeats"):
#   - Every bit says something about what happened: the player, the play, the
#     score, the streak, the stat, the opponent, what's next. Plain lines carry
#     at least a score or a name.
#   - Bits are built from pieces (#b_...#), so the same idea comes out in many
#     shapes; the Writer (news_words.Writer.fresh) never uses a shape twice in a
#     week or more than three times a season, and never repeats a finished bit.
#     A bit that can't be said freshly isn't posted.
#   - Accounts remember their takes (Blake, Oct 24: "yes, accounts remember"):
#     the *_crow, *_called, *_again lists are their follow-ups.
#
# Tone (Blake, Oct 23, kept Oct 24): PG-13. Trash talk, roasts, hot takes,
# sarcasm and memes; no swearing or slurs. Every account is invented; none
# imitates a real person. Opinions are allowed (that's the point); made-up
# facts aren't. Pieces are opinions or color, never facts.
#
# Facts for game reactions (engine/bitter.py, _game_facts): Wn Ln Wc Lc (winner
# and loser nickname and city), WN LN (in capitals), tag ltag (hashtags), score
# ws ls margin, star_last star_got (the winner's best player and what he did),
# lstar_last lstar_got (the loser's), wrec lrec, n_w n_l (streak words),
# goahead clock (the late go-ahead score), max_def (biggest deficit overcome),
# to_n (winner's takeaways), sk_n (winner's sacks), rw (winner's rushing yards),
# lsk_n (sacks the winner allowed), prev_week prev_score (the earlier meeting),
# next lnext (each side's next opponent), rematch_week, div, temp, wind, rnd
# (playoff round), champ (the title game's name), pen_n peny (loser's penalties).

