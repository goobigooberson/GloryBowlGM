# make_names.py
# Builds engine/name_data.py, the game's name pool, from REAL NFL rosters 1999-2025
# (tools/data/roster_*.csv.gz, nflverse open data): every player once, the first name
# he goes by (football_name: "Chris", not "Christopher") and his last name, counted.
# The game draws first and last names separately with these counts as odds, so common
# names stay common (Michael, Williams) and the rare ones show up about as often as in
# a real locker room. Players who entered the league from 2012 on count double, so the
# pool leans toward the names of today's players. First and last are drawn separately, so a
# made-up player now and then shares a real player's full name, as real people do (Blake, Oct
# 22: fine by chance). Coaches and other grown-ups get first names from players who entered
# before 2008 (ELDER_FIRST_COUNTS).
#
#   python tools/make_names.py        (rewrites engine/name_data.py)

import csv
import glob
import gzip
import re
from collections import Counter
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RECENT_FROM = 2012
RECENT_WEIGHT = 2
ELDER_BEFORE = 2008      # first names of players who entered before this: coaches', GMs' and other
                         # grown-ups' names (a 60-year-old coach isn't a Mekhi)


def clean_first(name):
    name = re.sub(r",?\s*(Jr|Sr|II|III|IV)\.?$", "", name.strip())
    return name.strip()


def main():
    seen = {}
    for fn in sorted(glob.glob(str(ROOT / "tools" / "data" / "roster_*.csv.gz"))):
        with gzip.open(fn, "rt", encoding="utf-8") as f:
            for x in csv.DictReader(f):
                pid = x.get("gsis_id") or x.get("full_name")
                if not pid or pid in seen:
                    continue
                first = clean_first(x.get("football_name") or x.get("first_name") or "")
                last = (x.get("last_name") or "").strip()
                if not first or not last or not re.fullmatch(r"[A-Za-z][A-Za-z'\-\. ]*", first + last):
                    continue
                year = x.get("rookie_year") or x.get("entry_year") or x.get("season") or "0"
                year = int(float(year)) if year.replace(".", "").isdigit() else 0
                seen[pid] = (first, last, RECENT_WEIGHT if year >= RECENT_FROM else 1, 0 < year < ELDER_BEFORE)
    firsts, lasts, elders = Counter(), Counter(), Counter()
    for first, last, w, elder in seen.values():
        firsts[first] += w
        if elder:
            elders[first] += 1
        lasts[last] += w
    out = [
        "# name_data.py",
        "# The game's name pool, from REAL NFL rosters 1999-2025 (nflverse open data):",
        f"# {len(seen):,} players, {len(firsts):,} first names, {len(lasts):,} last names. Each count is",
        f"# how many players had the name (those who entered the league from {RECENT_FROM} on count",
        f"# {RECENT_WEIGHT}x).",
        "#",
        "# Generated by tools/make_names.py; don't edit by hand unless you mean to.",
        "",
        "FIRST_COUNTS = {",
    ]
    out += [f"    {k!r}: {v}," for k, v in sorted(firsts.items(), key=lambda kv: (-kv[1], kv[0]))]
    out += ["}", "", "LAST_COUNTS = {"]
    out += [f"    {k!r}: {v}," for k, v in sorted(lasts.items(), key=lambda kv: (-kv[1], kv[0]))]
    out += ["}", "", f"# First names of players who entered before {ELDER_BEFORE} (coaches, GMs, media).", "ELDER_FIRST_COUNTS = {"]
    out += [f"    {k!r}: {v}," for k, v in sorted(elders.items(), key=lambda kv: (-kv[1], kv[0]))]
    out += ["}", ""]
    path = ROOT / "engine" / "name_data.py"
    path.write_text("\n".join(out), encoding="utf-8", newline="\n")
    print(f"wrote {path}: {len(firsts):,} first names, {len(lasts):,} last names")


if __name__ == "__main__":
    main()
